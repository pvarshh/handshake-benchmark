"""Emit numbers.tex: every number quoted in the paper text comes from these
macros, generated from the results files, so prose cannot silently diverge
from the data."""

from __future__ import annotations

SCEN = {"s1": "SOne", "s2": "STwo", "s3": "SThree", "s4a": "SFourA", "s4b": "SFourB", "s4c": "SFourC"}
PROT = {
    "mcp-legacy": "McpLegacy",
    "mcp-modern": "McpModern",
    "a2a": "Atoa",
    "acp": "Acp",
    "mcp-legacy-warm": "McpLegacyWarm",
    "mcp-modern-warm": "McpModernWarm",
    "mcp-pinned-warm": "McpPinnedWarm",
    "a2a-warm": "AtoaWarm",
    "acp-warm": "AcpWarm",
}
NET = {"local": "Local", "rtt50": "Rtt"}
TOKPROT = {"mcp-legacy": "McpLegacy", "mcp-modern": "McpModern", "a2a": "Atoa", "acp": "Acp"}


_WORDS = {1: "One", 10: "Ten", 50: "Fifty", 200: "TwoHundred"}


def _word(n: int) -> str:
    """Spell an inventory size: LaTeX macro names cannot contain digits."""
    if n not in _WORDS:
        raise KeyError(f"no macro-name spelling for inventory size {n}; "
                       f"add it to _WORDS")
    return _WORDS[n]


def _fmt_ms(v: float) -> str:
    if v < 0.05:
        return "0.0"
    if v < 100:
        return f"{v:.1f}"
    return f"{v:.0f}"


def emit(summary: dict, tok: dict, baseline: dict, n_runs: int, sweep_rows=None,
         inventory=None) -> str:
    lines = ["% Auto-generated by analysis/numbers.py - do not edit by hand."]

    def macro(name: str, value: str):
        lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    macro("NRuns", str(n_runs))
    for key, cell in summary.items():
        scen, prot, net = key.split(".")
        if scen not in SCEN or prot not in PROT:
            continue
        base = SCEN[scen] + PROT[prot] + NET[net]
        if "median_ms" in cell:
            macro(base + "Med", _fmt_ms(cell["median_ms"]))
            macro(base + "PNF", _fmt_ms(cell["p95_ms"]))
        if "ttf_median_ms" in cell:
            macro(base + "TtfMed", _fmt_ms(cell["ttf_median_ms"]))
        macro(base + "Rts", str(int(cell["round_trips_median"])))
        if cell.get("connections") is not None:
            macro(base + "Conns", str(int(cell["connections"])))
        if cell.get("wire_bytes_up") is not None:
            macro(base + "BytesUp", str(int(cell["wire_bytes_up"])))
            macro(base + "BytesDown", str(int(cell["wire_bytes_down"])))
        macro(base + "Retries", str(cell.get("retries_max", 0)))

    for p, name in TOKPROT.items():
        macro("Tok" + name, str(tok[p]["tokens"]))
        macro("TokBytes" + name, str(tok[p]["bytes"]))
        macro("Usd" + name, f"{tok[p]['usd_per_million_handshakes']:.0f}")

    if sweep_rows:
        import statistics as _st

        sweep_name = {"mcp-legacy": "McpLegacy", "mcp-modern": "McpModern", "a2a": "Atoa", "acp": "Acp"}
        rtts = sorted({r["rtt_ms"] for r in sweep_rows})
        for proto, sname in sweep_name.items():
            meds = []
            for rtt in rtts:
                ms = [r["handshake_ms"] for r in sweep_rows
                      if r["protocol"] == proto and r["rtt_ms"] == rtt
                      and r["handshake_ms"] is not None]
                meds.append((rtt, _st.median(ms)))
            xs, ys = [m[0] for m in meds], [m[1] for m in meds]
            xbar, ybar = sum(xs) / len(xs), sum(ys) / len(ys)
            slope = sum((x - xbar) * (y - ybar) for x, y in zip(xs, ys)) / sum(
                (x - xbar) ** 2 for x in xs)
            macro("Slope" + sname, f"{slope:.1f}")
        ns = [1 for r in sweep_rows if r["protocol"] == "a2a" and r["rtt_ms"] == rtts[0]]
        macro("SweepN", str(len(ns)))
        # cross-check: sweep 50ms medians vs the independently measured
        # S1 rtt50 cells (Table 2)
        deltas = []
        for proto in sweep_name:
            ms = [r["handshake_ms"] for r in sweep_rows
                  if r["protocol"] == proto and r["rtt_ms"] == 50
                  and r["handshake_ms"] is not None]
            cell = summary.get(f"s1.{proto}.rtt50", {}).get("median_ms")
            if ms and cell is not None:
                deltas.append(abs(_st.median(ms) - cell))
        if deltas:
            macro("SweepVsTableMaxDeltaMs", f"{max(deltas):.1f}")

    hw = [(c["median_ci_hi"] - c["median_ci_lo"]) / 2
          for c in summary.values() if "median_ci_lo" in c]
    if hw:
        macro("CiMaxHalfWidth", f"{max(hw):.1f}")
        macro("CiMedHalfWidth", f"{sorted(hw)[len(hw) // 2]:.2f}")
        macro("CiIters", "2{,}000")

    if inventory:
        inv_name = {"mcp": "Mcp", "a2a": "Atoa", "acp": "Acp"}
        for proto, sname in inv_name.items():
            d = inventory["protocols"][proto]
            macro("InvPerCap" + sname, f"{d['tokens_per_capability']:.0f}")
            for row in d["rows"]:
                # LaTeX macro names are letters only, so sizes are spelled out
                macro(f"Inv{sname}N{_word(row['n'])}",
                      f"{row['tokens']:,}".replace(",", "{,}"))
        # largest inventory as a share of a 200k-token context window
        biggest = max(
            inventory["protocols"][p_]["rows"][-1]["tokens"] for p_ in inv_name
        )
        macro("InvMaxCtxPct", f"{100.0 * biggest / 200_000:.0f}")
        macro("InvMaxN", str(inventory["sizes"][-1]))

    if "tcp-connect" in baseline:
        macro("BaselineTcpMed", f"{baseline['tcp-connect']['median_ms']:.2f}")
    if "tls13-handshake" in baseline:
        macro("BaselineTlsMed", f"{baseline['tls13-handshake']['median_ms']:.2f}")

    # Derived headline numbers
    def med(k):
        return summary.get(k, {}).get("median_ms")

    legacy_rtt, a2a_rtt = med("s1.mcp-legacy.rtt50"), med("s1.a2a.rtt50")
    if legacy_rtt and a2a_rtt:
        macro("HeadlineColdRatio", f"{legacy_rtt / a2a_rtt:.1f}")
    modern_rtt = med("s1.mcp-modern.rtt50")
    if legacy_rtt and modern_rtt:
        macro("McpModernSpeedup", f"{(1 - modern_rtt / legacy_rtt) * 100:.0f}")
    # amortized cost at k=100, rtt50
    for prot, cold_key, warm_key, name in [
        ("mcp-legacy", "s1.mcp-legacy.rtt50", "s2.mcp-legacy-warm.rtt50", "McpLegacy"),
        ("mcp-modern", "s1.mcp-modern.rtt50", "s2.mcp-modern-warm.rtt50", "McpModern"),
        ("mcp-pinned", "s1.mcp-modern.rtt50", "s2.mcp-pinned-warm.rtt50", "McpPinned"),
        ("a2a", "s1.a2a.rtt50", "s2.a2a-warm.rtt50", "Atoa"),
        ("acp", "s1.acp.rtt50", "s2.acp-warm.rtt50", "Acp"),
    ]:
        cold, warm = med(cold_key), med(warm_key)
        if cold is not None and warm is not None:
            macro("Amort" + name, _fmt_ms((cold + 99 * warm) / 100))
    return "\n".join(lines) + "\n"
